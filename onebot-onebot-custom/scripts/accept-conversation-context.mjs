import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';

const root = process.argv[2];
if (!root?.includes('/simulation-')) throw new Error('Supply an isolated simulation directory');
const calls = JSON.parse(await readFile(join(root, 'model-calls.json'), 'utf8'));
const textOf = value => typeof value === 'string' ? value : Array.isArray(value) ? value.map(part=>part.text??'').join('\n') : '';
const primary = calls.find(call=>call.scenario==='CASE_CONTEXT_FALLBACK' && call.agentId==='main' && call.model==='gemini-3.8-flash-high');
const secondary = calls.find(call=>call.scenario==='CASE_CONTEXT_FALLBACK' && call.model.startsWith('qwen') && JSON.stringify(call.messages).includes('你在给 QQ 回复做终审'));
assert.ok(primary && secondary);
const system = primary.messages.filter(message=>message.role==='system').map(message=>textOf(message.content)).join('\n');
const primaryWindow = system.split('[Shared conversation transcript]\n')[1]?.split('\n[End shared conversation transcript]')[0]?.split('\n').slice(1).join('\n');
const prompt = secondary.messages.filter(message=>message.role==='user').map(message=>textOf(message.content)).join('\n');
const secondaryWindow = prompt.split('最近对话实录与摘要（可能为空）：\n')[1]?.split('\n\n主模型最终回复：')[0];
assert.ok(primaryWindow && secondaryWindow);
assert.equal(primaryWindow, secondaryWindow);
assert.ok(primaryWindow.includes('CONTEXT_PRIMARY_INITIAL'));
const next = calls.find(call=>call.scenario==='CASE_CONTEXT_FINAL' && call.agentId==='main' && call.model==='gemini-3.8-flash-high');
assert.ok(next);
const nextInput = JSON.stringify(next.messages);
assert.ok(nextInput.includes('备用链路的模拟回复已经准备好。'));
assert.ok(!nextInput.includes('LLM request failed.'));
const db = new DatabaseSync(join(root, 'agents/main/agent/openclaw-agent.sqlite'), {readOnly:true});
const sid=db.prepare('SELECT current_session_id FROM session_nodes WHERE session_key=?').get('agent:main:onebot:direct:private:700000003').current_session_id;
const events=db.prepare('SELECT event_json FROM transcript_events WHERE session_id=? ORDER BY seq').all(sid).map(row=>JSON.parse(row.event_json).message).filter(Boolean);
const candidates=events.filter(message=>message.onebotConversation?.kind==='candidate');
const delivered=events.filter(message=>message.onebotConversation?.kind==='delivered');
assert.ok(candidates.length>=3);
assert.ok(candidates.every(message=>message.provider==='openclaw' && message.model==='gateway-injected'));
assert.ok(delivered.some(message=>message.onebotConversation.sourceModel.startsWith('novacode/qwen')));
assert.equal(new Set(delivered.map(message=>message.idempotencyKey)).size, delivered.length);
db.close();
const report={passed:true,realQqMessages:0,realBusinessWrites:0,identicalSharedWindow:true,sharedWindowBytes:Buffer.byteLength(primaryWindow,'utf8'),fallbackReadsPrimary:true,primaryReadsFallback:true,unsentCandidateExcluded:true,primaryCandidatesAudited:candidates.length,deliveredAssistantRecords:delivered.length};
await writeFile(join(root,'context-acceptance.json'),JSON.stringify(report,null,2)+'\n',{mode:0o600});
console.log(JSON.stringify(report));
